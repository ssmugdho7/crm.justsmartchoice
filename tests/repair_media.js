const {JSDOM}=require('jsdom');
const fs=require('node:fs'),assert=require('node:assert/strict');
const dom=new JSDOM('<a id="thumb" href="/admin/development/file/8" target="_blank"><img src="/admin/development/file/8"></a><img id="foreign" src="https://example.com/picture.png">',{url:'https://crm.justsmartchoice.com/admin/development/view/5',runScripts:'outside-only'});
const w=dom.window,d=w.document;
w.scRepairMediaLabels={preview:'Preview',close:'Close'};
w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
w.HTMLDialogElement.prototype.close=function(){this.open=false;this.dispatchEvent(new w.Event('close'));};
w.eval(fs.readFileSync('modules/toast_master/assets/js/repair-media.js','utf8'));
const img=d.querySelector('#thumb img');
const click=new w.MouseEvent('click',{bubbles:true,cancelable:true});img.dispatchEvent(click);
assert.ok(click.defaultPrevented,'Single click must not open a separate window before double click');
img.dispatchEvent(new w.MouseEvent('dblclick',{bubbles:true,cancelable:true}));
assert.ok(d.querySelector('dialog[open] img[src$="/file/8"]'));
d.querySelector('dialog img').dispatchEvent(new w.MouseEvent('click',{bubbles:true}));
assert.equal(d.querySelectorAll('dialog').length,0,'Single click restores the thumbnail view');
d.getElementById('thumb').dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',bubbles:true,cancelable:true}));
assert.ok(d.querySelector('dialog[open]'),'Keyboard users can open the preview');
d.querySelector('dialog button').click();
d.getElementById('foreign').dispatchEvent(new w.MouseEvent('dblclick',{bubbles:true}));
assert.equal(d.querySelectorAll('dialog').length,0,'Unrelated/off-origin images are excluded');
dom.window.close();
console.log('PASS double-click preview, single-click close, keyboard controls and file-origin boundary');
